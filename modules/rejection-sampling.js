/**
 * Rejection sampling: maps random bytes to character pool by discarding
 * values that would cause uneven distribution.
 *
 * Defines a maximum valid range that is a perfect multiple of pool.length.
 * Any random byte >= limit is discarded and a new byte is drawn.
 * This guarantees a perfectly uniform distribution.
 */

/**
 * Calculate the rejection limit for a given pool size.
 * Values >= limit are rejected.
 * @param {number} poolSize - Size of the character pool
 * @returns {number} The rejection limit
 */
export function rejectionLimit(poolSize) {
  return 256 - (256 % poolSize);
}

/**
 * Generate a frequency distribution using rejection sampling.
 * @param {string} pool - The character pool
 * @param {Uint8Array} randomBytes - Pre-generated random bytes (needs extra for rejections)
 * @param {number} sampleCount - Number of accepted samples desired
 * @returns {{ freq: Object, rejectedCount: number }} Frequency map and rejection count
 */
export function rejectionDistribution(pool, randomBytes, sampleCount) {
  const freq = {};
  for (let i = 0; i < pool.length; i++) {
    freq[pool[i]] = 0;
  }

  const limit = rejectionLimit(pool.length);
  let accepted = 0;
  let rejected = 0;
  let byteIndex = 0;

  while (accepted < sampleCount) {
    // If we run out of pre-generated bytes, generate more
    if (byteIndex >= randomBytes.length) {
      const extra = crypto.getRandomValues(new Uint8Array(Math.max(1024, sampleCount - accepted)));
      const newBytes = new Uint8Array(randomBytes.length + extra.length);
      newBytes.set(randomBytes);
      newBytes.set(extra, randomBytes.length);
      randomBytes = newBytes;
    }

    const byte = randomBytes[byteIndex++];

    if (byte < limit) {
      const char = pool[byte % pool.length];
      freq[char]++;
      accepted++;
    } else {
      rejected++;
    }
  }

  return { freq, rejectedCount: rejected };
}

/**
 * Generate a password using rejection sampling.
 * @param {string} pool - The character pool
 * @param {number} length - Password length
 * @returns {string} Generated password
 */
export function rejectionPassword(pool, length) {
  const limit = rejectionLimit(pool.length);
  let password = '';

  while (password.length < length) {
    const bytes = crypto.getRandomValues(new Uint8Array(length * 2));
    for (let i = 0; i < bytes.length && password.length < length; i++) {
      if (bytes[i] < limit) {
        password += pool[bytes[i] % pool.length];
      }
    }
  }

  return password;
}
